// Серверный шлюз платных возможностей. Ставится ПОСЛЕ middleware/auth.js на те
// роуты, которые входят в Pro (состав тарифа — в lib/capabilities.js).
//
// Раньше файл назывался requireAccess.js и знал только одно: «триал кончился —
// не пускать». Проверка была одна на всё, поэтому её нельзя было применить к
// разным функциям по-разному: запись бюджета закрывалась вместе с прогнозом,
// хотя вести бюджет человек должен и на бесплатном тарифе. Теперь шлюз
// параметризован именем возможности и спрашивает реестр, а не сравнивает план
// с литералом 'pro' — состав тарифов меняется в одном файле.
//
// Проверка живёт здесь, а не внутри каждого роута, чтобы её нельзя было забыть
// на новом эндпоинте: подключение шлюза видно в определении маршрута.
const ah = require('./asyncHandler');
const { loadEntitlement } = require('../lib/entitlement');

// ── Код ответа: 402, и это выбрано по фактическому коду опубликованного
// RuStore-клиента (versionCode 3), а не по вкусу.
//
// В его бандле (android/app/src/main/assets/public/static/js/main.7322ae73.js)
// обёртка запросов делает ровно одно ветвление по статусу:
//     if (!res.ok) { 401 === res.status && auth && logout(); throw ... }
// То есть logout() срабатывает ТОЛЬКО на 401. Любой другой код (402, 403, 500)
// обрабатывается одинаково: запрос не повторяется (retry обёрнут вокруг самого
// fetch и работает лишь когда запрос не дошёл до сервера), сессия сохраняется,
// локальные данные не трогаются.
//
// Почему 402, а не 403: 403 уже занят в routes/family.js под ошибку
// 'pro_required' (лимит участников на free-тарифе), и фронт показывает на неё
// текст «Общий бюджет на нескольких участников — в подписке Pro». Переиспользовать
// эту пару для других отказов значило бы показывать заведомо неверное сообщение.
// Отдельный статус разводит два разных отказа однозначно.
const DENIED_STATUS = 402;

// Аварийный выключатель на случай, если шлюз поведёт себя на проде не так, как
// ожидается (промежуточный прокси, неучтённая версия клиента). Выключается
// переменной окружения без деплоя — но, как и все настройки в этом проекте,
// требует перезапуска процесса (см. комментарий в lib/aiAccess.js).
// Значение по умолчанию — включено: ради этого шлюз и делался.
const gateEnabled = () => process.env.SUBSCRIPTION_GATE_ENABLED !== 'false';

/**
 * Middleware-фабрика: пускает дальше, только если возможность входит в тариф
 * пользователя. Всегда кладёт в req.entitlement полное право доступа — роуты
 * берут оттуда familyId вместо своего запроса за family_id.
 *
 * Для бесплатных возможностей (basicBudget) шлюз никогда не отказывает — но
 * ставить его всё равно стоит: это единая точка загрузки entitlement, и если
 * состав тарифов однажды изменится, менять нужно будет только реестр.
 *
 * @param {string} capability имя из lib/capabilities.js
 */
const requireCapability = capability => ah(async (req, res, next) => {
  const ent = await loadEntitlement(req.user.uid);
  if (!ent) return res.status(404).json({ error: 'no_family' });

  req.entitlement = ent;

  if (ent.can(capability)) return next();

  if (!gateEnabled()) {
    console.warn(
      `subscription gate OFF: пропускаю ${req.method} ${req.originalUrl} ` +
      `(возможность ${capability}) для семьи ${ent.familyId} с планом ${ent.plan}`
    );
    return next();
  }

  // error — историческое поле проекта (по нему собирается текст ошибки и в
  // старом, и в новом клиенте), code — машиночитаемый дубль. capability
  // добавлено новым ключом: старый клиент незнакомые поля игнорирует, а новый
  // показывает по нему контекстный paywall именно про эту функцию, а не общий
  // текст «пробный период закончился».
  return res.status(DENIED_STATUS).json({
    error: 'subscription_required',
    code: 'SUBSCRIPTION_REQUIRED',
    capability,
    plan: ent.plan,
    trialEndsAt: ent.trialEndsAt,
  });
});

module.exports = requireCapability;
module.exports.DENIED_STATUS = DENIED_STATUS;
module.exports.gateEnabled = gateEnabled;
