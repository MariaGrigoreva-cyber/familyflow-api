// Express 4 не ловит автоматически отклонённые промисы из async-обработчиков —
// необработанный reject (напр. кратковременный сбой БД) становится unhandled
// rejection и, начиная с Node 15+, роняет весь процесс целиком (все пользователи
// сразу, не только один запрос). Оборачиваем каждый async-хендлер этим врапером,
// чтобы ошибка шла в next(err) — обычному обработчику ошибок Express (и Sentry).
module.exports = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);
