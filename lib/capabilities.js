// Состав тарифов Free / Pro — ЕДИНСТВЕННОЕ место в проекте, где записано,
// какая возможность кому доступна.
//
// Зачем отдельный файл, а не проверки `plan === 'pro'` по коду. Раньше состав
// тарифа был размазан: лимит участников семьи считался в routes/family.js,
// запись бюджета — в шлюзе доступа (тогда middleware/requireAccess.js),
// прогноз и «А что если?» не
// проверялись на сервере вообще (фронт решал сам), а AI жил по своему
// allowlist'у беты и к тарифу отношения не имел. Чтобы поменять состав Free/Pro,
// нужно было найти все эти места и не забыть ни одного.
//
// Здесь — таблица «возможность → минимальный тариф», и всё остальное
// (middleware/requireCapability.js, routes/*, ответ GET /billing/status) читает
// её. Второго источника правды нет: сам ПЛАН по-прежнему считает computePlan
// в lib/billingLogic.js, этот модуль только раскладывает его на возможности.

// Тарифы, в порядке возрастания прав. trial намеренно приравнен к pro: во время
// пробного периода человек должен увидеть полную ценность Pro, иначе ему не за
// что платить после его окончания.
const FREE = 'free';
const PRO = 'pro';

// ── Реестр ───────────────────────────────────────────────────────────────────
// Ключ — код возможности, значение — минимальный тариф. Названия описывают
// ПОЛЬЗОВАТЕЛЬСКИЙ вопрос, на который отвечает функция, а не экран приложения:
// экраны переименовываются и переезжают, состав тарифа — нет.
const CAPABILITIES = {
  // ── Free: «что происходит с моими деньгами сейчас» ──────────────────────
  // Бесплатный тариф обязан оставаться самостоятельно полезным. Человек, у
  // которого кончился триал, продолжает вести бюджет: доходы, обязательные
  // расходы, недельный план, фактические траты, текущий остаток.
  basicBudget: FREE,      // чтение и запись снапшота бюджета (PUT /state)
  aiSupport: FREE,        // вопросы о том, как работает приложение (без личных данных)

  // ── Pro: «что будет дальше» ─────────────────────────────────────────────
  //
  // safeSpendable и forecast разделены намеренно, хотя считаются из одного и
  // того же прогноза (projectCashFlow). Это разные вопросы пользователя:
  //   safeSpendable — «сколько я могу потратить ПРЯМО СЕЙЧАС, ничего не сломав»
  //                   (одна цифра, ответ на сегодня);
  //   forecast      — «что будет в следующие недели» (ряд остатков вперёд).
  // Держать их одной возможностью значило бы, что состав тарифа нельзя изменить
  // по одному из этих вопросов, не задев второй.
  safeSpendable: PRO,     // свободный остаток сверх плана на сегодня
  forecast: PRO,          // прогноз движения денег вперёд: недели, месяцы, годы
  cashflowWarnings: PRO,  // предупреждения о будущей нехватке денег
  spendingCheck: PRO,     // «могу ли я сейчас потратить X»
  aiAssistant: PRO,       // ответы AI по личному финансовому плану
  scenarios: PRO,         // «а что если» — проверка решения до траты
  recommendations: PRO,   // персональные подсказки, что сделать с дефицитом
  budgetHealth: PRO,      // разбор здоровья бюджета
  familySharing: PRO,     // общий бюджет на нескольких участников
  multipleIncomes: PRO,   // несколько источников дохода на одного человека
};

const CAPABILITY_NAMES = Object.freeze(Object.keys(CAPABILITIES));
const FREE_CAPABILITIES = Object.freeze(CAPABILITY_NAMES.filter(n => CAPABILITIES[n] === FREE));
const PRO_CAPABILITIES = Object.freeze(CAPABILITY_NAMES.filter(n => CAPABILITIES[n] === PRO));

// Есть ли у плана платный доступ. trial и pro — да, free — нет. Ровно та же
// граница, что у entitlement.access; отдельной логики здесь нет.
const isPaidPlan = plan => plan === 'trial' || plan === 'pro';

/**
 * Доступна ли конкретная возможность на этом плане.
 * Неизвестное имя — всегда false: опечатка в коде роута не должна ОТКРЫВАТЬ
 * доступ (это худшая сторона ошибки), поэтому дефолт закрытый.
 */
function hasCapability(plan, name) {
  // Object.hasOwn, а не просто CAPABILITIES[name]: имена вроде 'toString' или
  // 'constructor' достались бы из прототипа Object и прошли бы проверку на
  // undefined, открыв доступ по случайному имени.
  if (typeof name !== 'string' || !Object.hasOwn(CAPABILITIES, name)) return false;
  return CAPABILITIES[name] === FREE || isPaidPlan(plan);
}

/**
 * Полная карта { имя: boolean } для этого плана. Уходит клиенту в
 * GET /billing/status — фронт рисует интерфейс по ней и своей копии таблицы
 * тарифов не держит.
 */
function capabilitiesFor(plan) {
  const out = {};
  for (const name of CAPABILITY_NAMES) out[name] = hasCapability(plan, name);
  return out;
}

module.exports = {
  FREE, PRO,
  CAPABILITIES, CAPABILITY_NAMES, FREE_CAPABILITIES, PRO_CAPABILITIES,
  isPaidPlan, hasCapability, capabilitiesFor,
};
