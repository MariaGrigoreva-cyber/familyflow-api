const APP_URL = (process.env.CORS_ORIGIN || '').split(',')[0].trim() || 'https://myfamilyflow.ru';

function buildMail({ body, cta, signoff }) {
  const text = [body.trim(), `${cta} ${APP_URL}`, signoff].filter(Boolean).join('\n\n');
  const html = [textToHtml(body), ctaButtonHtml(cta, APP_URL), signoff ? `<p>${escapeHtml(signoff)}</p>` : '']
    .filter(Boolean).join('\n');
  return { text, html };
}

