// Публичный адрес веб-приложения — единственное место, где он определяется.
//
// Зачем отдельный модуль. Раньше этот адрес брался как ПЕРВЫЙ элемент
// CORS_ORIGIN — в пяти местах, каждое своей копией `.split(',')[0]`. То есть
// переменная, которая по смыслу список разрешённых origin, заодно молча
// назначала, куда вернуть человека после оплаты, куда увести после входа через
// Яндекс ID и какие ссылки положить в письма.
//
// Связь была неочевидной и дорогой: дописать новый origin в начало списка —
// обычное, безобидное на вид действие — уводило платежи, письма и токен входа
// на чужой адрес. Особенно неприятно с /auth/yandex/callback: он отдаёт токен
// во фрагменте редиректа.
//
// Теперь адрес задаётся своей переменной APP_PUBLIC_URL и ни от чьего порядка
// не зависит. Рядом с ним в окружении уже живёт API_PUBLIC_URL — адрес самого
// API; имена намеренно парные.

// Куда вести, если не задано ничего. Это адрес приложения, а не лендинга:
// все ссылки, которые тут строятся (возврат из оплаты, подтверждение почты,
// письма), должны приводить человека именно в приложение. Раньше в
// lib/onboardingScheduler.js запасным значением стоял лендинг — расхождение,
// из-за которого одно и то же понятие вело в два разных места.
const DEFAULT_APP_URL = 'https://app.myfamilyflow.ru';

// Хвостовой слэш режем: вызывающий код дописывает к адресу `/#yandex_token=…`,
// и с ним получилось бы `//#…`.
const normalize = url => String(url).trim().replace(/\/+$/, '');

/**
 * Откуда берётся значение, по убыванию приоритета:
 *   1. APP_PUBLIC_URL — явно и однозначно;
 *   2. первый элемент CORS_ORIGIN — совместимость с окружениями, где новая
 *      переменная ещё не выставлена. Убирать этот путь нельзя до тех пор, пока
 *      APP_PUBLIC_URL не появится на всех стендах: иначе выкатка кода молча
 *      сломает ссылки в письмах и возврат из оплаты;
 *   3. DEFAULT_APP_URL.
 *
 * Значение '*' из CORS_ORIGIN адресом не считается — как URL оно бессмысленно.
 */
function appPublicUrl() {
  const explicit = normalize(process.env.APP_PUBLIC_URL || '');
  if (explicit) return explicit;

  const fromCors = normalize((process.env.CORS_ORIGIN || '').split(',')[0]);
  if (fromCors && fromCors !== '*') return fromCors;

  return DEFAULT_APP_URL;
}

/**
 * Задан ли адрес где-либо явно (переменной или через CORS_ORIGIN).
 *
 * Нужен ровно одному месту — /auth/verify-email: на неизвестном адресе оно не
 * редиректит, а показывает страницу «Email подтверждён». Само по себе значение
 * appPublicUrl() всегда валидно из-за дефолта, поэтому отличить «настроено» от
 * «взяли дефолт» иначе нельзя.
 */
function appPublicUrlConfigured() {
  if (normalize(process.env.APP_PUBLIC_URL || '')) return true;
  const fromCors = normalize((process.env.CORS_ORIGIN || '').split(',')[0]);
  return !!fromCors && fromCors !== '*';
}

module.exports = { appPublicUrl, appPublicUrlConfigured, DEFAULT_APP_URL };
