// Словесная формулировка детерминированного вывода приложения.
// Живёт отдельно, чтобы её использовали и боевой роут, и проверочный стенд —
// иначе стенд проверяет не то, что уходит пользователю (уже наступали).
// Готовый вывод формулируем СЛОВАМИ здесь, а не полагаемся на то, что модель
// правильно прочитает булево поле. С «помещается / не помещается» флага
// хватало, а вот «период не покрыт прогнозом» модель принимала за метаданные и
// всё равно выдавала вердикт о достаточности денег. Текст пишет сервер —
// клиент присылает только числа и даты, подделать формулировку он не может.
function decisionSentence(d) {
  if (d.type === 'spending_check') {
    return d.fitsFreeSpendable
      ? `трата ${d.requestedAmount} помещается в свободный остаток ${d.freeSpendableNow}; после неё свободного остатка останется ${d.differenceAfterSpend}`
      : `трата ${d.requestedAmount} НЕ помещается в свободный остаток ${d.freeSpendableNow}; не хватает ${Math.abs(d.differenceAfterSpend)}`;
  }
  // period_check
  if (d.status === 'needs_date') {
    return 'период, о котором спрашивает пользователь, не имеет конкретной даты'
      + ' — определить его границу невозможно. Нужно попросить пользователя назвать'
      + ' примерную дату или месяц и НЕ давать никакой оценки достаточности денег'
      + ' до уточнения';
  }
  return d.coveredByForecast
    ? `спрошенный период (до ${d.askedPeriodEnd}) целиком внутри прогноза (до ${d.forecastThrough})`
    : `спрошенный период (до ${d.askedPeriodEnd}) выходит за границу прогноза`
      + (d.forecastThrough ? ` (прогноз заканчивается ${d.forecastThrough})` : ' (прогноза нет)')
      + '; данных об этом периоде нет, поэтому вывод о том, хватит ли денег, делать нельзя —'
      + ' нужно прямо сказать пользователю, что таких данных нет, и не давать никакой оценки достаточности';
}

module.exports = { decisionSentence };
