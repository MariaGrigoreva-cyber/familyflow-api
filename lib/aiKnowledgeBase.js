// Доверенный блок контекста: в промпт уходит НЕ то, что прислал клиент, а
// только наша собственная строка из SCREEN_LABELS. Для неизвестного экрана
// блок не добавляется вовсе — лучше никакого контекста, чем выдуманный.
function buildScreenContext(screen) {
  const label = SCREEN_LABELS[screen];
  if (!label) return '';
  return [
    '## ТЕКУЩИЙ КОНТЕКСТ',
    `Пользователь сейчас находится на экране «${label}».`,
    'Используй эту информацию только если она помогает понять вопрос пользователя.',
    'Не считай, что любой вопрос обязательно относится к текущему экрану.',
  ].join('\n');
}

